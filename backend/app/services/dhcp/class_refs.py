"""Who refers to a DHCP client-class NAME (#2285).

``DHCPPool.class_restriction`` is a free string rendered verbatim into Kea's
``client-class``. Kea accepts a pool bound to a class it does not define and
simply never matches it, so a rename or delete that leaves a pool behind does
not fail anywhere: the pool silently stops serving. These helpers let the
write paths refuse that (the same shape as the DNS ACL reference guard) and
let the bundle build say so when it happens anyway.
"""

from __future__ import annotations

import re
import uuid
from collections.abc import Iterable

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.dhcp import DHCPClientClass, DHCPPool, DHCPScope
from app.models.dhcp_device_policy import DHCPDevicePolicy

# Classes Kea defines itself. ``HA_*`` / ``VENDOR_CLASS_*`` are Kea's
# auto-assigned families; ``SPAWN_*`` is created by operator tests.
KEA_BUILTIN_CLASSES = frozenset({"ALL", "KNOWN", "UNKNOWN", "BOOTP", "DROP"})
_BUILTIN_PREFIXES = ("HA_", "VENDOR_CLASS_", "SPAWN_")
# Generated by the bundle: pxe-<8hex>-<8hex>, voip-<8hex>.
_GENERATED_RE = re.compile(r"^(pxe-[0-9a-f]{8}-[0-9a-f]{8}|voip-[0-9a-f]{8})$")


def is_builtin_or_generated(name: str) -> bool:
    return (
        name in KEA_BUILTIN_CLASSES
        or name.startswith(_BUILTIN_PREFIXES)
        or bool(_GENERATED_RE.match(name))
    )


async def pools_restricted_to(
    db: AsyncSession, group_id: uuid.UUID, name: str
) -> list[tuple[str, str, str]]:
    """``(scope name, start_ip, end_ip)`` of every pool in the group bound to ``name``."""
    rows = (
        await db.execute(
            select(DHCPScope.name, DHCPPool.start_ip, DHCPPool.end_ip)
            .join(DHCPScope, DHCPPool.scope_id == DHCPScope.id)
            .where(DHCPScope.group_id == group_id, DHCPPool.class_restriction == name)
            .order_by(DHCPScope.name, DHCPPool.start_ip)
        )
    ).all()
    return [(r[0] or "", str(r[1]), str(r[2])) for r in rows]


async def classes_testing_membership(
    db: AsyncSession, group_id: uuid.UUID, name: str, exclude_id: uuid.UUID | None = None
) -> list[str]:
    """Other client classes whose test is ``member('<name>')``-dependent."""
    needles = (f"'{name}'", f'"{name}"')
    rows = (
        await db.execute(
            select(DHCPClientClass.id, DHCPClientClass.name, DHCPClientClass.match_expression)
            .where(DHCPClientClass.group_id == group_id)
            .order_by(DHCPClientClass.name)
        )
    ).all()
    out: list[str] = []
    for cid, cname, expr in rows:
        if cid == exclude_id or not expr or "member(" not in expr:
            continue
        if any(n in expr for n in needles):
            out.append(cname)
    return out


def describe_pools(pools: list[tuple[str, str, str]]) -> str:
    shown = ", ".join(f"{s}-{e}" + (f" ({n})" if n else "") for n, s, e in pools[:5])
    more = f" and {len(pools) - 5} more" if len(pools) > 5 else ""
    return f"{shown}{more}"


async def known_class_names(db: AsyncSession, group_id: uuid.UUID) -> set[str]:
    """Operator class names + device-policy class names in the group."""
    ops = (
        (await db.execute(select(DHCPClientClass.name).where(DHCPClientClass.group_id == group_id)))
        .scalars()
        .all()
    )
    pols = (
        (
            await db.execute(
                select(DHCPDevicePolicy.class_name).where(DHCPDevicePolicy.group_id == group_id)
            )
        )
        .scalars()
        .all()
    )
    return set(ops) | set(pols)


def dangling_restrictions(
    pool_classes: Iterable[tuple[str, str]], defined: set[str]
) -> list[tuple[str, str]]:
    """``(pool label, class)`` for restrictions naming a class nothing defines."""
    return [
        (label, c)
        for label, c in pool_classes
        if c and c not in defined and not is_builtin_or_generated(c)
    ]
