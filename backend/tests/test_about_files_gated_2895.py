"""The About page's static files are refused to anyone without a session (#2895).

NOTICE, LICENSE and the npm notice list are generated by the frontend build
and served by the web tier's nginx, not the api. Someone probing the server
from outside must not learn which libraries and tools it runs, so:

* the frontend image keeps them OUTSIDE the nginx web root, where no other
  location (the SPA fallback, the static-asset regex) can hand them out; and
* both nginx configs (the image's own, used by compose, and the Helm chart's
  TLS one, used by the chart and the appliance) serve them only behind an
  ``auth_request`` to the api's session check.

The end-to-end proof is a curl against a running stack; this pins the config
so a later edit cannot quietly drop the gate.
"""

from __future__ import annotations

import pathlib
import re

import pytest

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
_DOCKERFILE = _REPO_ROOT / "frontend" / "Dockerfile"
_CONFIGS = (
    _REPO_ROOT / "frontend" / "default.conf.template",
    _REPO_ROOT / "charts" / "spatiumddi" / "templates" / "frontend-tls-config.yaml",
)
_LEGAL_DIR = "/usr/share/spatiumddi/legal"

pytestmark = pytest.mark.skipif(
    not _DOCKERFILE.exists(), reason="frontend/ not present in this checkout (dev container)"
)


def _location(conf: str, header: str) -> str:
    """The body of the location block opening with ``header``."""
    start = conf.index(header)
    # The block's own closing brace sits alone on its line; a ``}`` inside a
    # ``${VAR}`` does not.
    match = re.compile(r"\n\s*}\n").search(conf, start)
    assert match is not None, header
    return conf[start : match.end()]


def test_the_files_are_copied_outside_the_web_root() -> None:
    text = _DOCKERFILE.read_text(encoding="utf-8")
    assert f"COPY --from=builder /app/dist-legal {_LEGAL_DIR}" in text
    # The web root receives dist/ only, and the build writes the legal files
    # to dist-legal/, a sibling, so nothing public carries them.
    assert "COPY --from=builder /app/dist /usr/share/nginx/html" in text


@pytest.mark.parametrize("path", _CONFIGS, ids=lambda p: p.name)
def test_legal_location_is_behind_the_session_gate(path: pathlib.Path) -> None:
    conf = path.read_text(encoding="utf-8")

    block = _location(conf, "location ^~ /legal/ {")
    assert "auth_request /_about_session;" in block
    assert f"alias {_LEGAL_DIR}/;" in block
    # A missing file is a 404, never the SPA's index.html.
    assert "try_files" not in block

    gate = _location(conf, "location = /_about_session {")
    assert "internal;" in gate
    assert "/api/v1/about/session;" in gate
    assert "proxy_pass_request_body off;" in gate


@pytest.mark.parametrize("path", _CONFIGS, ids=lambda p: p.name)
def test_no_other_location_serves_the_files(path: pathlib.Path) -> None:
    conf = path.read_text(encoding="utf-8")

    # Exactly one directive reaches the directory, and it is the gated one.
    directives = [
        line.strip()
        for line in conf.splitlines()
        if _LEGAL_DIR in line and not line.strip().startswith("#")
    ]
    assert directives == [f"alias {_LEGAL_DIR}/;"]
    assert f"root {_LEGAL_DIR}" not in conf
    # The pre-#2895-rework public path is gone.
    assert "/third-party-licenses.txt" not in conf
