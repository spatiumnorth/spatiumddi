"""The watchdog does not bring a revoked node's roles back (#2808).

The revoked teardown deletes the role chart and deliberately keeps
``role-compose.env`` (a re-registration restores the roles from it, #2801).
The watchdog read the assigned roles from that file, found their pods gone and
healed them by re-applying the chart, so DNS and DHCP started again on a node
taken out of service, every time the watchdog fell due. Seen on a one-node rig:
the role chart was applied 31 s after the teardown and 29 s before the node was
approved again.

Now the watchdog and the heartbeat's role apply share one gate
(``approval_state.role_services_hold``): only an approved node runs its role
services. A held node reports its missing services as ``held``, not
``missing``, and heals nothing. The first accepted heartbeat after the hold
applies the roles even when the apply stamp still names the env the teardown
un-applied, since the watchdog no longer does it.
"""

from __future__ import annotations

import json
import types
import uuid
from pathlib import Path

import httpx
import pytest
import structlog
from structlog.testing import capture_logs

from spatium_supervisor import (
    appliance_state,
    approval_state,
    heartbeat,
    k8s_api,
    service_lifecycle,
    watchdog,
)

ROLE_ENV = (
    "# Auto-generated by spatium-supervisor — do not hand-edit.\n"
    "COMPOSE_PROFILES=dhcp,dns-bind9\n"
    "AGENT_GROUP=default\n"
    "DNS_ENGINE=bind9\n"
    "DHCP_AGENT_GROUP=default\n"
    "DHCP_NETWORK_MODE=host\n"
)


@pytest.fixture
def no_role_pods(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> list[list[str]]:
    """A kubeapi that is up and runs none of this node's role pods (the
    revoked teardown took them down), a role env naming dhcp + dns-bind9, and
    a recorder for every role apply the watchdog makes."""
    body = json.dumps({"items": []}).encode()
    monkeypatch.setattr(k8s_api, "_request", lambda method, path, **_kw: (200, body))
    monkeypatch.setattr(k8s_api, "check_kubeapi_ready", lambda *a, **k: True)
    monkeypatch.setattr(watchdog, "_status_history", {})
    (tmp_path / "role-compose.env").write_text(ROLE_ENV, encoding="utf-8")
    applied: list[list[str]] = []

    def fake_apply(profiles: list[str], env_file: Path) -> service_lifecycle.LifecycleResult:
        applied.append(list(profiles))
        return service_lifecycle.LifecycleResult(state="ready", started=tuple(profiles))

    monkeypatch.setattr(watchdog, "apply_role_assignment", fake_apply)
    return applied


def _events(logs: list[dict], name: str) -> list[dict]:
    return [e for e in logs if e["event"] == f"supervisor.watchdog.{name}"]


# --- the gate ----------------------------------------------------------------


@pytest.mark.parametrize(
    ("persisted", "held"),
    [("approved\n", None), ("revoked\n", "revoked"), (None, "pending")],
)
def test_only_an_approved_node_may_run_its_role_services(
    tmp_path: Path, persisted: str | None, held: str | None
) -> None:
    if persisted is not None:
        (tmp_path / "approval-state").write_text(persisted, encoding="utf-8")
    assert approval_state.role_services_hold(tmp_path) == held


# --- the watchdog pass -------------------------------------------------------


@pytest.mark.parametrize("held_by", ["revoked", "pending"])
def test_a_held_node_heals_nothing_and_says_why(
    tmp_path: Path, no_role_pods: list[list[str]], held_by: str
) -> None:
    """REGRESSION (#2808): the watchdog re-applied the role chart."""
    with capture_logs() as logs:
        health = watchdog.check_health(tmp_path / "role-compose.env", held_by=held_by)
    assert no_role_pods == []
    assert not _events(logs, "heal_attempted")
    assert not _events(logs, "missing_services")
    said = _events(logs, "heal_skipped_not_approved")
    assert len(said) == 1
    assert said[0]["approval_state"] == held_by
    assert sorted(said[0]["held"]) == ["dhcp-kea", "dns-bind9"]
    # Down on purpose, not a fault: no red ``missing`` chip in the Fleet UI.
    assert {svc: e["status"] for svc, e in health.items()} == {
        "dhcp-kea": "held",
        "dns-bind9": "held",
    }
    assert all(e["held_by"] == held_by for e in health.values())


def test_a_held_node_whose_kubeapi_is_gone_reports_held(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, no_role_pods: list[list[str]]
) -> None:
    """A revoked member its peers fenced out reaches no kubeapi."""
    monkeypatch.setattr(k8s_api, "check_kubeapi_ready", lambda *a, **k: False)
    health = watchdog.check_health(tmp_path / "role-compose.env", held_by="revoked")
    assert {e["status"] for e in health.values()} == {"held"}
    assert no_role_pods == []


def test_an_approved_node_still_heals_its_missing_services(
    tmp_path: Path, no_role_pods: list[list[str]]
) -> None:
    with capture_logs() as logs:
        health = watchdog.check_health(tmp_path / "role-compose.env", held_by=None)
    assert no_role_pods == [["dhcp", "dns-bind9"]]
    assert len(_events(logs, "heal_attempted")) == 1
    assert not _events(logs, "heal_skipped_not_approved")
    assert {e["status"] for e in health.values()} == {"missing"}
    assert all("held_by" not in e for e in health.values())


# --- the heartbeat drives the watchdog through the gate ----------------------


def _stub_heartbeat(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(appliance_state, "collect", dict)
    monkeypatch.setattr(appliance_state, "detect_deployment_kind", lambda: "appliance")
    monkeypatch.setattr(appliance_state, "read_firewall_state", dict)
    monkeypatch.setattr(heartbeat, "probe_port_conflicts", dict)
    monkeypatch.setattr(heartbeat, "_capabilities_payload", dict)
    monkeypatch.setattr(heartbeat, "_effective_control_plane_url", lambda cfg: "http://cp.invalid")
    monkeypatch.setattr(heartbeat, "load_cert", lambda d: None)
    monkeypatch.setattr(
        heartbeat,
        "tear_down_supervised_services",
        lambda: service_lifecycle.LifecycleResult(state="ready"),
    )
    monkeypatch.setattr(heartbeat, "_last_watchdog_at", 0.0)
    monkeypatch.setattr(heartbeat, "_cached_role_health", {})


def _revoked_heartbeat(tmp_path: Path) -> list[dict]:
    """One heartbeat the control plane refuses as a revocation, from a node
    whose watchdog is due. Answers both the #2798 marker and the legacy
    detail, so it reads as a revocation with or without that change."""

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(
            403,
            headers={"X-Spatium-Revocation": "revoked"},
            json={"detail": "Appliance has been revoked."},
        )

    cfg = types.SimpleNamespace(heartbeat_interval_seconds=0, state_dir=tmp_path)
    with (
        capture_logs() as logs,
        httpx.Client(transport=httpx.MockTransport(handler)) as client,
    ):
        heartbeat.heartbeat_once(
            cfg, uuid.uuid4(), "tok", None, client, structlog.get_logger()  # type: ignore[arg-type]
        )
    return logs


def test_a_revoked_heartbeat_does_not_bring_the_roles_back(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, no_role_pods: list[list[str]]
) -> None:
    """REGRESSION (#2808), the path the rig took: revoked, the role env kept,
    the role pods gone, the watchdog due on the next heartbeat."""
    _stub_heartbeat(monkeypatch)
    (tmp_path / "approval-state").write_text("revoked\n", encoding="utf-8")
    logs = _revoked_heartbeat(tmp_path)
    assert approval_state.read_state(tmp_path) == "revoked"
    assert no_role_pods == [], "the watchdog re-applied a revoked node's roles"
    assert not _events(logs, "heal_attempted")
    assert _events(logs, "heal_skipped_not_approved")[0]["approval_state"] == "revoked"
    # #2801 still needs the env to restore the roles on re-register.
    assert (tmp_path / "role-compose.env").read_text(encoding="utf-8") == ROLE_ENV


def test_an_approved_node_s_heartbeat_still_heals(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, no_role_pods: list[list[str]]
) -> None:
    """The watchdog runs while the heartbeat body is built, before the POST,
    so an approved node heals even on a heartbeat the control plane refuses
    once (a single strike is not a revocation)."""
    _stub_heartbeat(monkeypatch)
    (tmp_path / "approval-state").write_text("approved\n", encoding="utf-8")
    _revoked_heartbeat(tmp_path)
    assert no_role_pods == [["dhcp", "dns-bind9"]]


# --- approved again: the first accepted heartbeat applies --------------------


@pytest.fixture
def lifecycle(monkeypatch: pytest.MonkeyPatch, tmp_path: Path):
    """The heartbeat's role apply, with the apply and the label reconcile
    recorded instead of sent, and a stamp saying this env was applied."""
    env_path = tmp_path / "role-compose.env"
    env_path.write_text(ROLE_ENV, encoding="utf-8")
    applied: list[list[str]] = []

    def fake_apply(profiles: list[str], env: Path) -> service_lifecycle.LifecycleResult:
        applied.append(list(profiles))
        return service_lifecycle.LifecycleResult(state="ready", started=tuple(profiles))

    monkeypatch.setattr(heartbeat, "apply_role_assignment", fake_apply)
    monkeypatch.setattr(heartbeat, "reconcile_node_labels", lambda *a, **k: (True, None))
    _, key = heartbeat._role_apply_due(tmp_path, ROLE_ENV, env_path)
    heartbeat._write_last_apply_hash(tmp_path, key)
    return types.SimpleNamespace(env_path=env_path, applied=applied)


def test_a_steady_heartbeat_still_skips_the_apply(tmp_path: Path, lifecycle) -> None:
    heartbeat._run_role_lifecycle(tmp_path, ["dhcp", "dns-bind9"], ROLE_ENV, lifecycle.env_path)
    assert lifecycle.applied == []


def test_the_first_heartbeat_after_the_hold_applies_despite_the_stamp(
    tmp_path: Path, lifecycle
) -> None:
    """The teardown un-applied the env the stamp names. Without #2801's stamp
    clearing, the stamp alone would skip the apply, and the watchdog no
    longer heals a held node, so the roles would stay down after approval."""
    with capture_logs() as logs:
        heartbeat._run_role_lifecycle(
            tmp_path, ["dhcp", "dns-bind9"], ROLE_ENV, lifecycle.env_path, force=True
        )
    assert lifecycle.applied == [["dhcp", "dns-bind9"]]
    assert [e for e in logs if e["event"] == "supervisor.heartbeat.lifecycle_forced"]


# --- end to end: revoked, then the first accepted heartbeat ------------------


def test_the_first_accepted_heartbeat_after_a_revoke_applies_the_roles(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, no_role_pods: list[list[str]]
) -> None:
    """REGRESSION (#2808): revoked → (watchdog holds) → approved. The roles
    come back on the first accepted heartbeat, not five minutes later, even
    though the stamp still names the same env."""
    _stub_heartbeat(monkeypatch)
    monkeypatch.setattr(appliance_state, "detect_appliance_variant", lambda: "data-plane")
    for name in [n for n in dir(appliance_state) if n.startswith("maybe_fire_")]:
        monkeypatch.setattr(appliance_state, name, lambda *a, **k: False)
    monkeypatch.setattr(heartbeat, "_dispatch_firewall", lambda *a, **k: None)
    monkeypatch.setattr(heartbeat, "reconcile_node_labels", lambda *a, **k: (True, None))
    heartbeat_applies: list[list[str]] = []

    def fake_apply(profiles: list[str], env: Path) -> service_lifecycle.LifecycleResult:
        heartbeat_applies.append(list(profiles))
        return service_lifecycle.LifecycleResult(state="ready", started=tuple(profiles))

    monkeypatch.setattr(heartbeat, "apply_role_assignment", fake_apply)
    env_path = tmp_path / "role-compose.env"
    assignment = {
        "roles": ["dhcp", "dns-bind9"],
        "dns_group_name": "default",
        "dns_engine": "bind9",
        "dhcp_group_name": "default",
        "dhcp_network_mode": "host",
    }

    def accepted() -> list[dict]:
        def handler(request: httpx.Request) -> httpx.Response:
            return httpx.Response(200, json={"role_assignment": assignment})

        cfg = types.SimpleNamespace(heartbeat_interval_seconds=0, state_dir=tmp_path)
        with (
            capture_logs() as logs,
            httpx.Client(transport=httpx.MockTransport(handler)) as client,
        ):
            heartbeat.heartbeat_once(
                cfg, uuid.uuid4(), "tok", None, client, structlog.get_logger()  # type: ignore[arg-type]
            )
        return logs

    # Approved and serving: the first accepted heartbeat applies and stamps.
    accepted()
    assert heartbeat_applies == [["dhcp", "dns-bind9"]]
    rendered = env_path.read_text(encoding="utf-8")
    # Steady state skips.
    accepted()
    assert len(heartbeat_applies) == 1

    # Revoked (the teardown took the pods down). The strikes before the flip
    # were built while the node still read approved, so they may heal; once
    # revoked, a due watchdog holds.
    for _ in range(approval_state.REVOCATION_STRIKE_LIMIT):
        _revoked_heartbeat(tmp_path)
    assert approval_state.read_state(tmp_path) == "revoked"
    no_role_pods.clear()
    monkeypatch.setattr(heartbeat, "_last_watchdog_at", 0.0)
    _revoked_heartbeat(tmp_path)
    assert no_role_pods == [], "the watchdog re-applied a revoked node's roles"
    assert env_path.read_text(encoding="utf-8") == rendered

    # Approved again: the first accepted heartbeat applies at once. (Whether
    # that is the force or a stamp the teardown dropped, #2801, the roles must
    # be back on this heartbeat.)
    accepted()
    assert approval_state.read_state(tmp_path) == "approved"
    assert heartbeat_applies == [["dhcp", "dns-bind9"]] * 2
    assert no_role_pods == [], "the role apply, not a watchdog heal, brought them back"
    # And the one after skips again.
    accepted()
    assert len(heartbeat_applies) == 2


def test_an_invalidated_watchdog_is_due_right_after_boot(monkeypatch: pytest.MonkeyPatch) -> None:
    """``time.monotonic()`` counts from boot. ``_last_watchdog_at = 0.0`` (never
    ran, or invalidated after a role apply) was compared like a timestamp, so
    in the first 5 min of host uptime the watchdog was not due at all. A fresh
    CI runner is exactly that host, which is how this was found."""
    monkeypatch.setattr(heartbeat.time, "monotonic", lambda: 60.0)
    monkeypatch.setattr(heartbeat, "_last_watchdog_at", 0.0)
    assert heartbeat._watchdog_check_due() is True
    monkeypatch.setattr(heartbeat, "_last_watchdog_at", 30.0)
    assert heartbeat._watchdog_check_due() is False
